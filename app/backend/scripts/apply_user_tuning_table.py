def update_scratch_files():
    print("=== 1. Updating Scratch JSON Files ===")
    chunk_to_rules = {}
    for r in RULES:
        for cid in r["chunks"]:
            if cid not in chunk_to_rules:
                chunk_to_rules[cid] = []
            chunk_to_rules[cid].append(r)

    source_files = sorted(glob.glob(str(SCRATCH_DIR / "vat*.json")))
    total_updated_chunks = 0

    for fpath in source_files:
        with open(fpath, "r", encoding="utf-8") as f:
            chunks = json.load(f)

        file_modified = False
        for chunk in chunks:
            cid = chunk.get("chunk_id")
            if cid in chunk_to_rules:
                meta = chunk.setdefault("metadata", {})
                b_kws = meta.setdefault("boost_keywords", [])
                t_kws = meta.setdefault("tfidf_keywords", [])
                u_int = meta.setdefault("user_intents", [])

                for r in chunk_to_rules[cid]:
                    for kw in r["keywords"]:
                        if kw not in b_kws:
                            b_kws.append(kw)
                    for intent in r["intents"]:
                        if intent not in u_int:
                            u_int.append(intent)

                file_modified = True
                total_updated_chunks += 1

        if file_modified:
            with open(fpath, "w", encoding="utf-8") as f:
                json.dump(chunks, f, ensure_ascii=False, indent=2)
            print(f"  [OK] Updated: {Path(fpath).name}")

    print(f"Total chunk instances updated in scratch: {total_updated_chunks}")


