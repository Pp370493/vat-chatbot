def legal_basis(row_id: str, group: str) -> str:
    if group == "OUT_OF_SCOPE":
        return "-"
    if group == "HIGH_RISK_SECTION_6":
        return A6 + (" / 159 ข้อ 5(4)" if row_id in ("RISK_029", "RISK_030", "RISK_031", "RISK_032") else "")
    n = int(row_id.split("_")[1])
    return next(basis for rng, basis in DEFAULT_BY_PREFIX if n in rng)


